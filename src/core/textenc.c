/* 1252's 0x80-0x9F (the rest of its upper half is Latin-1 as it stands) */
static const unsigned short CP1252[32] = { 0x20ac, 0xfffd, 0x201a, 0x0192, 0x201e, 0x2026, 0x2020, 0x2021, 0x02c6, 0x2030, 0x0160, 0x2039, 0x0152, 0xfffd, 0x017d, 0xfffd,
  0xfffd, 0x2018, 0x2019, 0x201c, 0x201d, 0x2022, 0x2013, 0x2014, 0x02dc, 0x2122, 0x0161, 0x203a, 0x0153, 0xfffd, 0x017e, 0x0178 };

unsigned textenc_char(int cp, unsigned char c) {
  if (c < 0x80) return c;
  if (cp <= CP_1252 || cp > CP_1258) return c < 0xa0 ? CP1252[c - 0x80] : c;
  return CP[cp - 1][c - 0x80];
}
static int one_of(const char *l, const char *const *set) { for (int i = 0; set[i]; i++) if (!strcmp(l, set[i])) return 1; return 0; }
static int letter(unsigned char c) { return (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') || c >= 0xc0; }
int textenc_pick(const unsigned char *b, size_t n, const char *lang) {
  static const char *const L1250[] = { "hun", "cze", "slo", "pol", "hrv", "slv", "bos", "rum", "alb", NULL }, *const L1251[] = { "rus", "ukr", "bul", "mac", "bel", NULL },
    *const L1256[] = { "ara", "per", "urd", NULL }, *const L1257[] = { "est", "lav", "lit", NULL }, *const NONE[] = { "und", "mul", "zxx", NULL };
  const char *l = lang ? lang : ""; int srp = !strcmp(l, "srp");
  if (*l && !srp && !one_of(l, NONE)) {
    if (one_of(l, L1250)) return CP_1250;
    if (one_of(l, L1251)) return CP_1251;
    if (!strcmp(l, "gre")) return CP_1253;
    if (!strcmp(l, "tur") || !strcmp(l, "aze")) return CP_1254;
    if (!strcmp(l, "heb")) return CP_1255;
    if (one_of(l, L1256)) return CP_1256;
    if (one_of(l, L1257)) return CP_1257;
    if (!strcmp(l, "vie")) return CP_1258;
    return CP_1252; }
  /* from the text. Mostly letters above ASCII: an alphabet of its own. Cyrillic writes in lower case (0xE0-0xFF) with
     ы ь э ю я (0xFB-0xFF) or, in Serbian, Macedonian and Ukrainian, ј љ њ ћ ђ і ї є (0x80-0xBF); Greek puts its accented
     ά έ ή ί (0xDC-0xDF) inside lower-case words; Arabic has as many letters below 0xE0 as above; Hebrew's are 0xE0-0xFA */
  static const unsigned char CYR[] = { 0x80, 0x81, 0x8a, 0x8c, 0x8d, 0x8e, 0x8f, 0x90, 0x9a, 0x9c, 0x9d, 0x9e, 0x9f, 0xa1, 0xa2, 0xa3, 0xa5, 0xa8, 0xaa, 0xaf, 0xb2, 0xb3, 0xb4, 0xb8, 0xba, 0xbc, 0xbd, 0xbe, 0xbf };
  size_t hi = 0, lo = 0, up = 0, tail = 0, cyr = 0, tonos = 0, e50 = 0, e52 = 0, e54 = 0, sz = 0, ro = 0;
  for (size_t i = 0; i < n; i++) { unsigned char c = b[i], p = i ? b[i - 1] : 0, x = i + 1 < n ? b[i + 1] : 0; int nearL = letter(p) || letter(x);
    if (c < 0x80) { unsigned char k = c | 32; lo += k >= 'a' && k <= 'z'; continue; }
    if (c >= 0xc0) { hi++; up += c < 0xe0; tail += c >= 0xfb; tonos += c >= 0xdc && c <= 0xdf && p >= 0xe0 && x >= 0xe0; }
    else if ((p >= 0xc0 || x >= 0xc0) && memchr(CYR, c, sizeof CYR)) cyr++;
    /* Latin. 1250 on its own marks: the bytes 1252 leaves empty (Ť Ź ť); next to a letter, those that are symbols in
       1252 but letters in 1250 (ł ą ş ż ź ľ Ł Ą Ş Ż Ľ for ³ ¹ º ¿ Ÿ ¾ £ ¥ ª ¯ ¼; ż only after one: ¿ opens Spanish
       questions), ţ đ (þ ð: Icelandic alone); ě inside a word (ì ends Italian ones); š ž, the same in both pages but
       Central European; Hungarian ő ű Ő Ű (Portuguese õ comes before e or s, French û is rare). à À ç Ç count for 1252.
       Turkish (1254): ı ğ ş İ Ğ Ş next to letters, with no š ž and no Romanian ş ă */
    if (c == 0x9a || c == 0x9e || c == 0x8a || c == 0x8e) sz++;
    if (c == 0xba || c == 0xaa || c == 0xe3 || c == 0xc3) ro++;
    if (nearL && (c == 0xfd || c == 0xf0 || c == 0xfe || c == 0xdd || c == 0xd0 || c == 0xde)) e54++;
    if (c == 0x8d || c == 0x8f || c == 0x9d) e50 += 2;
    else if (c == 0xbf ? letter(p) : nearL && (c == 0xa3 || c == 0xa5 || c == 0xaa || c == 0xaf || c == 0xb3 || c == 0xb9 || c == 0xba || c == 0xbc || c == 0xbe || c == 0x9f || c == 0xfe || c == 0xf0)) e50++;
    else if (c == 0xec && letter(p) && letter(x)) e50++;
    else if (c == 0x9a || c == 0x9e || c == 0x8a || c == 0x8e || c == 0xfb || c == 0xdb || ((c == 0xf5 || c == 0xd5) && (x | 32) != 'e' && (x | 32) != 's')) e50++;
    else if (c == 0xe0 || c == 0xc0 || c == 0xe7 || c == 0xc7) e52++; }
  if (hi > lo) {
    if (srp) return CP_1251;
    if (tonos >= 2 && tonos * 50 >= hi) return CP_1253;
    if (up * 10 >= hi * 3) return CP_1256;
    if (!tail && !cyr && up * 20 < hi) return CP_1255;
    return CP_1251; }
  if (srp) return CP_1250;
  if (e54 >= 3 && !sz && ro * 3 < e54) return CP_1254;
  return e50 >= 3 && e50 > 2 * e52 ? CP_1250 : CP_1252;
}
