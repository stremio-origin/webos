#!/usr/bin/env python3
# tools/gen-waitlines.py <the approved loading texts .md> : writes src/core/waitlines_pools.h (every pool as one table)
import sys, os
src = open(sys.argv[1], encoding='utf-8').read().split('\n')
heads = {'Signing in':'SIGNIN','Choosing the best stream':'CHOOSE','Peer step':'PEERS','File list step':'FILES','Pieces step':'PIECES','Live channels':'LIVE',
 'Morning':'MORNING','Afternoon':'AFTERNOON','After work':'AFTERWORK','Evening':'EVENING','Late night,':'LATE','Weekend, any time':'WEEKEND',
 'Binge:':'BINGE','Film:':'FILM','First episode today':'FIRSTTODAY','Resume:':'RESUME','Late night binge':'LATEBINGE','Weekend binge':'WEEKENDBINGE',
 'Friday night':'FRIDAY','Samsung':'SAMSUNG','Android phone':'PHONE'}
subs = {'Generic':'', 'OLED,':'_OLED','QNED,':'_QNED','NanoCell,':'_NANO','Shield,':'_SHIELD','Sony,':'_SONY','Chromecast,':'_CHROMECAST','Fire TV,':'_FIRETV','Xiaomi,':'_XIAOMI','Philips,':'_PHILIPS','TCL,':'_TCL'}
pools = {}; cur = sub = None
for ln in src:
    if ln.startswith('## ') or ln.startswith('---'): cur = sub = None; continue
    if ln.startswith('### '):
        h = ln[4:]; cur = sub = None
        for k, v in heads.items():
            if h.startswith(k): cur = v; break
        if h.startswith('LG'): cur = 'LG'
        if h.startswith('Android TV'): cur = 'ATV'
        continue
    if cur in ('LG', 'ATV'):
        for k, v in subs.items():
            if ln.startswith(k): sub = cur + v
    if ln.startswith('- ') and cur:
        name = sub if cur in ('LG', 'ATV') else cur
        if name: pools.setdefault(name, []).append(ln[2:].strip())
order = ['SIGNIN','CHOOSE','PEERS','FILES','PIECES','LIVE','MORNING','AFTERNOON','AFTERWORK','EVENING','LATE','WEEKEND','BINGE','FILM','FIRSTTODAY','RESUME',
 'LATEBINGE','WEEKENDBINGE','FRIDAY','LG','LG_OLED','LG_QNED','LG_NANO','SAMSUNG','ATV','ATV_SHIELD','ATV_SONY','ATV_CHROMECAST','ATV_FIRETV','ATV_XIAOMI',
 'ATV_PHILIPS','ATV_TCL','PHONE']
pools['OLD'] = ["Warming up the pixels…","Asking the internet nicely…","Untangling the cables…",
 "Convincing the bits to line up…","Finding the remote. Oh, you have it.","Rewinding the tape… just kidding","Dimming the lights…",
 "Polishing the frames…","Telling the actors to get ready…","Silencing phones in the theatre…",
 "Loading the plot twist…","Feeding the hamsters that run the servers…","Adjusting the volume knob for drama…",
 "Rolling the opening credits…","This is the part where you grab a snack"]   # the player's old lines, translated everywhere: a plain stream's loading lines and every language's fallback ("Almost there. Probably.", "Popcorn status: ready. Stream status: almost." and "Good things come to those who buffer" left out: they claimed progress)
order.append('OLD')
for k in order:
    assert pools.get(k), 'no lines for ' + k
    for x in pools[k]: assert k == 'OLD' or len(x) <= 60, (k, x)
def c(s): return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('…', '\\xe2\\x80\\xa6').replace('’', '\\xe2\\x80\\x99') + '"'
out = ["/* generated by tools/gen-waitlines.py from the approved loading texts, and the player's old 18 lines (WLP_OLD): edit the texts, then regenerate */", 'enum {',
       '  ' + ', '.join('WLP_' + k for k in order) + ', WLP_N };', 'static const char *const WL_LINES[] = {']
starts = []; n = 0
for k in order: starts.append(n); out.append('  /* %s */ %s,' % (k, ', '.join(c(x) for x in pools[k]))); n += len(pools[k])
out += ['};', '#define WL_NLINES %d' % n, 'static const unsigned short WL_START[WLP_N + 1] = { %s, %d };' % (', '.join(map(str, starts)), n)]
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
open(os.path.join(root, 'src/core/waitlines_pools.h'), 'w').write('\n'.join(out) + '\n')
print(n, 'lines;', ', '.join('%s %d' % (k, len(pools[k])) for k in order))
